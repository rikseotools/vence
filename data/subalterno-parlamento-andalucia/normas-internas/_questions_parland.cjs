function buildExplanation(item) {
  const letter = L[item.c];
  const wrong = L.filter((_, i) => i !== item.c);
  const bullets = wrong.map((l, i) => `- **${l}** es incorrecta: ${item.bad[i]}`).join('\n');
  return `> ${item.cita}\n\n**Por qué ${letter} es correcta:** ${item.why}\n\n${bullets}`;
}

(async () => {
  const out = {};
  for (const key of Object.keys(Q)) {
    const lawId = imported[key].law_id;
    let n = 0;
    const dist = [0, 0, 0, 0];
    for (const item of Q[key]) {
      const art = (await sql`SELECT id FROM articles WHERE law_id=${lawId} AND article_number=${item.art}`)[0];
      if (!art) throw new Error(`Artículo ${item.art} no encontrado en ${key}`);
      await sql`INSERT INTO questions (question_text, option_a, option_b, option_c, option_d, correct_option, explanation, primary_article_id, difficulty, lifecycle_state, topic_review_status, deactivation_reason, tags)
        VALUES (${item.q}, ${item.o[0]}, ${item.o[1]}, ${item.o[2]}, ${item.o[3]}, ${item.c}, ${buildExplanation(item)}, ${art.id}, 'medium', 'draft', 'pending', 'Pendiente de revisión post-generación IA', ${['ia_generada', TAG]})`;
      dist[item.c]++;
      n++;
    }
    out[key] = { questions: n, distribucion: { A: dist[0], B: dist[1], C: dist[2], D: dist[3] } };
    console.log(`[${key}] preguntas draft=${n} distribución A/B/C/D=${dist.join('/')}`);
  }
  fs.writeFileSync(`${SP}/questions.json`, JSON.stringify(out, null, 1));
  await sql.end();
})();
